export const buildToneUserPrompt = (input: {
  article: PublicCurationArticleDto;
  recipes: StaticRecipe[];
}): string => {
  const { article, recipes } = input;
  const recipeBlock = recipes
    .map(
      (r, i) =>
        `${i + 1}. ${r.title}${r.description ? `\n   설명: ${r.description}` : ""}`
    )
    .join("\n");

  return `[큐레이션 원본]
title: ${article.title}
description: ${article.description ?? ""}
category: ${article.category ?? ""}

[큐레이션 본문 (markdown, 참고용 — 그대로 복사 금지, 톤·구조 변형)]
${article.contentMdx}

[묶인 레시피 ${recipes.length}개 — 이 순서대로 ## 섹션. 영양·계량 수치는 박지 말 것]
${recipeBlock}

위 입력으로 톤 결에 맞춰 markdown 본문을 출력하라. 마지막 ## 섹션 본문 뒤 \`---\` 한 줄 잊지 말 것.`;
};
